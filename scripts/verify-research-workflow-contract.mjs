assert.deepEqual(welch.payload, { missingCount: 0, groupACount: 3, groupBCount: 3, meanDifference: -4, standardError: 1.632993, tStatistic: -2.44949, degreesOfFreedom: 2.56, pValue: 0.106367, alpha: 0.05, significant: false, test: "UNPAIRED_WELCH" });
const paired = runDeterministicAnalysis({ ...fixtureBinding, method: "TWO_GROUP_COMPARISON", parameters: { ...inferenceParameters, pairing: "PAIRED", test: "STUDENT" }, groupA: [1, 2, 3], groupB: [1, 2, 4] });
