const fixtureBinding = { datasetSha256: "a".repeat(64), analysisPlanHash: "b".repeat(64) };
const inferenceParameters = { pairing: "UNPAIRED", tail: "TWO_SIDED", alpha: 0.05, missingValuePolicy: "COMPLETE_CASE", precision: 6, rounding: "HALF_EVEN" };
const pearson = runDeterministicAnalysis({ ...fixtureBinding, method: "CORRELATION", parameters: { ...inferenceParameters, correlation: "PEARSON" }, x: [1, 2, 3, 4], y: [2, 4, 6, 8] });
