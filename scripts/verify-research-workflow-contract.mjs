assert.deepEqual(spearman.payload, { missingCount: 0, count: 3, correlation: -0.5, correlationType: "SPEARMAN", tStatistic: -0.57735, degreesOfFreedom: 1, pValue: 0.666667, alpha: 0.05, significant: false });
const student = runDeterministicAnalysis({ ...fixtureBinding, method: "TWO_GROUP_COMPARISON", parameters: { ...inferenceParameters, test: "STUDENT" }, groupA: [1, 2, 3], groupB: [4, 5, 6] });
assert.deepEqual(student.payload, { missingCount: 0, groupACount: 3, groupBCount: 3, meanDifference: -3, standardError: 0.816497, tStatistic: -3.674235, degreesOfFreedom: 4, pValue: 0.021312, alpha: 0.05, significant: true, test: "UNPAIRED_STUDENT" });
